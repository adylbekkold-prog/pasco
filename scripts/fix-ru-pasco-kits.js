// 1. Read both files
const ky = readJson(KY_FILE)
const ru = readJson(RU_FILE)

// 2. Copy PASCO kits from Kyrgyz, applying Russian translations
const kits = (ky.pasco_kits || []).map((kit) => {
  const t = KIT_RU[kit.id] || {}
  return {
    ...kit,
    name: t.name || kit.name,
    description: t.description || kit.description,
    name_ru: t.name || kit.name,
    description_ru: t.description || kit.description,
  }
})

// 3. Copy PASCO kit components from Kyrgyz, applying Russian translations
const components = (ky.pasco_kit_components || []).map((comp) => {
  const t = COMP_RU[comp.id] || {}
  return {
    ...comp,
    name: t.name || comp.name,
    description: t.desc || comp.description,
    storage_location: t.storage || comp.storage_location,
    name_ru: t.name || comp.name,
    description_ru: t.desc || comp.description,
    storage_location_ru: t.storage || comp.storage_location,
  }
})

// 4. Update the Russian data file
ru.pasco_kits = kits
ru.pasco_kit_components = components

// 5. Write the complete Russian file
writeJson(RU_FILE, ru)

