/**
 * Script: fix-ru-pasco-kits.js
 *
 * Fixes the Russian PASCO kits data by copying the complete PASCO kit data
 * (with photos) from the Kyrgyz file into the Russian file, and translating
 * the names/descriptions from Kyrgyz to Russian.
 *
 * The Kyrgyz file (local-db.ky.json) contains the full rich data with photos,
 * while the Russian file (local-db.ru.json) only had basic/stale data without
 * photos. This script copies the structure/photos from Kyrgyz and applies
 * Russian translations.
 */

const fs = require('fs')
const path = require('path')

const DATA_DIR = path.join(__dirname, '..', 'data')
const KY_FILE = path.join(DATA_DIR, 'local-db.ky.json')
const RU_FILE = path.join(DATA_DIR, 'local-db.ru.json')

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

function writeJson(file, data) {
  fs.writeFileSync(file, JSON.stringify(data, null, 2), 'utf8')
}

